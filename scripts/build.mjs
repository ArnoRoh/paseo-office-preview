import { createRequire } from 'node:module';
import { build } from 'esbuild';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const result = await build({
  entryPoints: ['server/reader.ts'], bundle: true, write: false,
  platform: 'node', target: 'node22', format: 'cjs', minify: true,
  legalComments: 'inline', metafile: true,
});
await mkdir('server/generated', { recursive: true });
// Paseo evaluates CommonJS bundles without a module filename. Resolve local assets at install time.
await writeFile('server/generated/module-root.ts', `// Generated locally; excluded from packages.\nexport default ${JSON.stringify(createRequire(import.meta.url).resolve('pdfjs-dist/package.json'))};\n`);
await writeFile('server/generated/reader-source.ts',
  `// Generated by npm run build.\nexport default ${JSON.stringify(result.outputFiles[0].text)};\n`);

// Keep each bundled dependency's license with the worker distributed to users.
const packages = new Set();
for (const file of Object.keys(result.metafile.inputs)) {
  const match = file.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//);
  if (match) packages.add(match[1]);
}
const notices = [];
for (const directory of [...packages].sort()) {
  const metadata = JSON.parse(await readFile(path.join(directory, 'package.json'), 'utf8'));
  const names = (await readdir(directory)).filter(name => /^(licen[sc]e|copying|notice)(\.|$)/i.test(name));
  notices.push(`${metadata.name} ${metadata.version} (${metadata.license ?? 'See license'})\n`);
  for (const name of names) notices.push(await readFile(path.join(directory, name), 'utf8'));
}
await writeFile('server/generated/THIRD_PARTY_NOTICES.txt', notices.join('\n\n'));
